create extension if not exists pgcrypto;

-- ------------------------------------------------------------
-- 1. PERFILES VINCULADOS A SUPABASE AUTH
-- ------------------------------------------------------------

create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    username text not null unique,
    display_name text not null,
    phone text,
    role text not null default 'CLIENT'
        check (role in ('CLIENT', 'WORKSHOP')),
    created_at_ms bigint not null default ((extract(epoch from now()) * 1000)::bigint)
);

create or replace function public.edmotor_handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    v_username text;
    v_display_name text;
    v_phone text;
begin
    v_username := lower(coalesce(
        new.raw_user_meta_data ->> 'username',
        split_part(new.email, '@', 1)
    ));
    v_display_name := coalesce(
        new.raw_user_meta_data ->> 'display_name',
        v_username
    );
    v_phone := nullif(new.raw_user_meta_data ->> 'phone', '');

    -- Los registros públicos siempre nacen como CLIENT.
    -- El rol WORKSHOP se asigna manualmente desde SQL Editor.
    insert into public.profiles (
        id, username, display_name, phone, role
    ) values (
        new.id, v_username, v_display_name, v_phone, 'CLIENT'
    )
    on conflict (id) do nothing;

    return new;
end;
$$;

drop trigger if exists edmotor_auth_user_created on auth.users;
create trigger edmotor_auth_user_created
after insert on auth.users
for each row execute procedure public.edmotor_handle_new_user();

create or replace function public.edmotor_is_workshop()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.profiles
        where id = auth.uid()
          and role = 'WORKSHOP'
    );
$$;

create or replace function public.edmotor_is_client()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.profiles
        where id = auth.uid()
          and role = 'CLIENT'
    );
$$;

grant execute on function public.edmotor_is_workshop() to authenticated;
grant execute on function public.edmotor_is_client() to authenticated;

alter table public.profiles enable row level security;
drop policy if exists profiles_read_own_or_workshop on public.profiles;
create policy profiles_read_own_or_workshop
on public.profiles for select
to authenticated
using (id = auth.uid() or public.edmotor_is_workshop());

-- ------------------------------------------------------------
-- 2. PEDIDOS Y DETALLE DE PEDIDOS
-- ------------------------------------------------------------

create table if not exists public.orders (
    id integer generated by default as identity primary key,
    client_auth_id uuid not null references public.profiles(id) on delete restrict,
    client_name text not null,
    client_username text not null,
    client_phone text,
    status text not null default 'PENDING'
        check (status in ('PENDING', 'CONFIRMED', 'REJECTED')),
    total_cop bigint not null check (total_cop >= 0),
    created_at_ms bigint not null default ((extract(epoch from now()) * 1000)::bigint),
    updated_at_ms bigint not null default ((extract(epoch from now()) * 1000)::bigint),
    confirmed_by_auth_id uuid references public.profiles(id) on delete set null,
    confirmed_at_ms bigint
);

create index if not exists orders_client_auth_id_idx
    on public.orders(client_auth_id);
create index if not exists orders_status_idx
    on public.orders(status);
create index if not exists orders_created_at_ms_idx
    on public.orders(created_at_ms desc);

create table if not exists public.order_items (
    id integer generated by default as identity primary key,
    order_id integer not null references public.orders(id) on delete cascade,
    product_id integer not null,
    product_name text not null,
    category text not null,
    unit_price_cop bigint not null check (unit_price_cop >= 0),
    quantity integer not null check (quantity > 0),
    subtotal_cop bigint not null check (subtotal_cop >= 0)
);

create index if not exists order_items_order_id_idx
    on public.order_items(order_id);

alter table public.orders enable row level security;
alter table public.order_items enable row level security;

drop policy if exists orders_read_owner_or_client on public.orders;
create policy orders_read_owner_or_client
on public.orders for select
to authenticated
using (
    client_auth_id = auth.uid()
    or public.edmotor_is_workshop()
);

drop policy if exists order_items_read_owner_or_client on public.order_items;
create policy order_items_read_owner_or_client
on public.order_items for select
to authenticated
using (
    exists (
        select 1
        from public.orders o
        where o.id = order_items.order_id
          and (
              o.client_auth_id = auth.uid()
              or public.edmotor_is_workshop()
          )
    )
);

-- El pedido y sus artículos se insertan juntos en una transacción SQL.
create or replace function public.create_order(
    p_total_cop bigint,
    p_items jsonb
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
    v_profile public.profiles%rowtype;
    v_order_id integer;
    v_item jsonb;
    v_quantity integer;
    v_unit_price bigint;
    v_subtotal bigint;
begin
    select * into v_profile
    from public.profiles
    where id = auth.uid();

    if not found or v_profile.role <> 'CLIENT' then
        raise exception 'Solo un cliente autenticado puede crear pedidos.';
    end if;

    if p_total_cop < 0 or jsonb_typeof(p_items) <> 'array'
       or jsonb_array_length(p_items) = 0 then
        raise exception 'El pedido no contiene productos válidos.';
    end if;

    insert into public.orders (
        client_auth_id, client_name, client_username, client_phone,
        status, total_cop, created_at_ms, updated_at_ms
    ) values (
        auth.uid(), v_profile.display_name, v_profile.username, v_profile.phone,
        'PENDING', p_total_cop,
        (extract(epoch from now()) * 1000)::bigint,
        (extract(epoch from now()) * 1000)::bigint
    )
    returning id into v_order_id;

    for v_item in select value from jsonb_array_elements(p_items)
    loop
        v_quantity := (v_item ->> 'quantity')::integer;
        v_unit_price := (v_item ->> 'unit_price_cop')::bigint;
        v_subtotal := (v_item ->> 'subtotal_cop')::bigint;

        if v_quantity <= 0 or v_unit_price < 0 or v_subtotal < 0 then
            raise exception 'Un artículo del pedido contiene valores inválidos.';
        end if;

        insert into public.order_items (
            order_id, product_id, product_name, category,
            unit_price_cop, quantity, subtotal_cop
        ) values (
            v_order_id,
            (v_item ->> 'product_id')::integer,
            v_item ->> 'product_name',
            coalesce(v_item ->> 'category', ''),
            v_unit_price,
            v_quantity,
            v_subtotal
        );
    end loop;

    return v_order_id;
end;
$$;

create or replace function public.confirm_order(p_order_id integer)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
    v_rows integer;
begin
    if not public.edmotor_is_workshop() then
        raise exception 'Solo EdMotor puede confirmar pedidos.';
    end if;

    update public.orders
    set status = 'CONFIRMED',
        confirmed_by_auth_id = auth.uid(),
        confirmed_at_ms = (extract(epoch from now()) * 1000)::bigint,
        updated_at_ms = (extract(epoch from now()) * 1000)::bigint
    where id = p_order_id
      and status = 'PENDING';

    get diagnostics v_rows = row_count;
    if v_rows <> 1 then
        raise exception 'El pedido no existe o ya fue procesado.';
    end if;

    return true;
end;
$$;

create or replace function public.reject_order(p_order_id integer)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
    v_rows integer;
begin
    if not public.edmotor_is_workshop() then
        raise exception 'Solo EdMotor puede rechazar pedidos.';
    end if;

    update public.orders
    set status = 'REJECTED',
        updated_at_ms = (extract(epoch from now()) * 1000)::bigint
    where id = p_order_id
      and status = 'PENDING';

    get diagnostics v_rows = row_count;
    if v_rows <> 1 then
        raise exception 'El pedido no existe o ya fue procesado.';
    end if;

    return true;
end;
$$;

revoke all on function public.create_order(bigint, jsonb) from public;
revoke all on function public.confirm_order(integer) from public;
revoke all on function public.reject_order(integer) from public;
grant execute on function public.create_order(bigint, jsonb) to authenticated;
grant execute on function public.confirm_order(integer) to authenticated;
grant execute on function public.reject_order(integer) to authenticated;

