create table if not exists public.appointments (
    id bigint generated by default as identity primary key,
    client_auth_id uuid not null references public.profiles(id) on delete restrict,
    client_name text not null,
    client_username text not null,
    client_phone text,
    vehicle_brand text not null,
    vehicle_model text not null,
    vehicle_year integer not null,
    vehicle_plate text not null default '',
    scheduled_at_ms bigint not null,
    duration_minutes integer not null default 60
        check (duration_minutes between 15 and 240),
    description text not null,
    status text not null default 'PENDING'
        check (status in ('PENDING', 'CONFIRMED', 'REJECTED')),
    created_at_ms bigint not null default ((extract(epoch from now()) * 1000)::bigint),
    updated_at_ms bigint not null default ((extract(epoch from now()) * 1000)::bigint),
    reviewed_by_auth_id uuid references public.profiles(id) on delete set null
);

create index if not exists appointments_client_auth_id_idx
    on public.appointments(client_auth_id);
create index if not exists appointments_status_idx
    on public.appointments(status);
create index if not exists appointments_scheduled_at_ms_idx
    on public.appointments(scheduled_at_ms);

alter table public.appointments enable row level security;

-- Permisos SQL mínimos para las operaciones autenticadas.
grant usage on schema public to authenticated;
grant select on public.profiles, public.orders, public.order_items, public.appointments to authenticated;
grant insert on public.appointments to authenticated;
grant usage, select on all sequences in schema public to authenticated;

drop policy if exists appointments_read_client_or_workshop on public.appointments;
create policy appointments_read_client_or_workshop
on public.appointments for select
to authenticated
using (
    client_auth_id = auth.uid()
    or public.edmotor_is_workshop()
);

drop policy if exists appointments_client_create on public.appointments;
create policy appointments_client_create
on public.appointments for insert
to authenticated
with check (
    client_auth_id = auth.uid()
    and public.edmotor_is_client()
    and status = 'PENDING'
);

-- La aceptación revisa el solapamiento de una hora dentro de la misma
-- transacción, evitando que dos solicitudes ocupen el mismo espacio.
create or replace function public.accept_appointment(p_appointment_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
    v_target public.appointments%rowtype;
    v_rows integer;
begin
    if not public.edmotor_is_workshop() then
        raise exception 'Solo EdMotor puede confirmar citas.';
    end if;

    -- Serializa confirmaciones para evitar que dos dispositivos acepten
    -- simultáneamente dos citas en el mismo espacio de tiempo.
    perform pg_advisory_xact_lock(184467);

    select * into v_target
    from public.appointments
    where id = p_appointment_id
    for update;

    if not found or v_target.status <> 'PENDING' then
        raise exception 'La solicitud no existe o ya fue procesada.';
    end if;

    if exists (
        select 1
        from public.appointments a
        where a.status = 'CONFIRMED'
          and a.id <> p_appointment_id
          and a.scheduled_at_ms < v_target.scheduled_at_ms
                + (v_target.duration_minutes * 60000)
          and a.scheduled_at_ms + (a.duration_minutes * 60000)
                > v_target.scheduled_at_ms
    ) then
        raise exception 'Ese horario ya está ocupado. Selecciona otra hora.';
    end if;

    update public.appointments
    set status = 'CONFIRMED',
        reviewed_by_auth_id = auth.uid(),
        updated_at_ms = (extract(epoch from now()) * 1000)::bigint
    where id = p_appointment_id
      and status = 'PENDING';

    get diagnostics v_rows = row_count;
    if v_rows <> 1 then
        raise exception 'No fue posible confirmar la cita.';
    end if;

    return true;
end;
$$;

